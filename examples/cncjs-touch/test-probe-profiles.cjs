'use strict';
const assert=require('assert').strict;
const model=require('./touch/probe-model'),manager=require('./touch/probe-profiles');
const p=model.empty(),initial={profiles:[p],selected:0,removed:null};
const first=manager.create(initial),second=manager.create(first);
assert.equal(initial.profiles.length,1);assert.equal(first.profiles[1].name,'Nouvelle sonde (2)');assert.equal(second.profiles[2].name,'Nouvelle sonde (3)');
let saved=manager.save(first,1,{...p,name:'Plaque fine',thickness:3.25,faceX:-2.5},false);
assert.equal(saved.selected,1);assert.equal(first.profiles[1].thickness,null);
let copied=manager.duplicate(saved,1,false);
assert.equal(copied.profiles[2].name,'Copie · Plaque fine');assert.equal(copied.profiles[2].thickness,3.25);
copied.profiles[2].thickness=7;assert.equal(saved.profiles[1].thickness,3.25);
const again=manager.duplicate(copied,1,false);assert.equal(again.profiles[3].name,'Copie · Plaque fine (2)');
const long=manager.save(initial,0,{...p,name:'A'.repeat(60)},false);const longCopy=manager.duplicate(long,0,false);assert(longCopy.profiles[1].name.length<=60);
assert.throws(()=>manager.duplicate(initial,-1,false),/introuvable/);
const demo=manager.duplicate(initial,-1,true);assert.equal(demo.profiles[1].thickness,10);
assert.throws(()=>manager.remove(initial,0),/au moins/);assert.throws(()=>manager.remove(demo,-1),/introuvable/);
const before=JSON.stringify(saved),deleted=manager.remove(saved,1);
assert.equal(JSON.stringify(saved),before);assert.equal(deleted.profiles.length,1);assert.equal(deleted.selected,0);assert.equal(deleted.removed.profile.name,'Plaque fine');
// Simulate a reload: restoration uses persisted data, not object identity or old callbacks.
const restored=manager.restore(JSON.parse(JSON.stringify(deleted)));
assert.deepEqual(restored,saved);assert.equal(restored.removed,null);
const nameConflict=manager.save(deleted,0,{...p,name:'Plaque fine'},false);
assert.throws(()=>manager.restore(nameConflict),/nom/);assert.equal(nameConflict.removed.profile.thickness,3.25);
let full=initial;for(let i=0;i<7;i++)full=manager.create(full);
for(const fn of [()=>manager.create(full),()=>manager.duplicate(full,0,false),()=>manager.save(full,-1,model.demo(),true)])assert.throws(fn,/8 profils/);
const slot=manager.remove(full,3);assert.equal(manager.create(slot).profiles.length,8);assert.throws(()=>manager.restore(manager.create(slot)),/8 profils/);
assert.throws(()=>manager.save(saved,0,{...p,name:'PLAQUE FINE'},false),/nom/);
assert.throws(()=>manager.save(saved,0,{...p,thickness:0},false));
assert.throws(()=>manager.save(saved,0,{...p,directionX:2},false));
assert.throws(()=>manager.save(initial,-1,model.demo(),false));
for(const index of [null,NaN,0.5,-2,99,'0'])assert.throws(()=>manager.remove(saved,index));
const removedFirst=manager.remove(again,0),removedNext=manager.remove(removedFirst,1);
assert.equal(removedNext.removed.profile.name,'Copie · Plaque fine');
assert.equal(manager.restore(removedNext).profiles[1].name,'Copie · Plaque fine');
// A removal saved at an index past the end (list shortened since) is restored at the end;
// a corrupted removal index is refused without changing anything.
const shortened={...JSON.parse(JSON.stringify(deleted)),removed:{...deleted.removed,index:5}};
const atEnd=manager.restore(shortened);assert.equal(atEnd.profiles.at(-1).name,'Plaque fine');assert.equal(atEnd.selected,atEnd.profiles.length-1);
for(const index of [-1,1.5,'1',null])assert.throws(()=>manager.restore({...shortened,removed:{...shortened.removed,index}}),/invalide/);
assert.equal(shortened.removed.index,5);
console.log('PASS: profile creation/copies/unique names, saved values, capacity, deletion/restore across reload, conflicts and immutable failures; no machine transport.');
